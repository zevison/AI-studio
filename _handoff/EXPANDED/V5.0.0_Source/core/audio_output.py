"""Safe, local-only soundtrack policy for paid video outputs.

Provider video creation is NEVER invoked here. Audio is changed only after the
completed provider task's file has been downloaded into the local outputs folder.
"""
from __future__ import annotations
import os
import re
import subprocess
from pathlib import Path
from . import media

MODES={'original':'保留参考视频原音频','uploaded':'使用已上传音频','model':'由模型生成新音频','silent':'无声视频'}


def normalize(mode, *, legacy_audio=True):
    if mode in MODES:return mode
    if mode is not None:raise ValueError('仅支持已确认的自动音频处理方式')
    return 'model' if legacy_audio else 'silent'


# Determine soundtrack from user-supplied media and actual user wording, not UI settings.
# Avoid treating general references to "music rhythm" or video analysis as a
# demand for new generated sounds. The asset IDs are frozen into the preview.
_SILENT=("无声视频", "静音", "不需要声音", "不要声音", "不要音频", "删除声音", "移除音频", "去掉原声")
_ORIGINAL=("保留原声", "保持原声", "原视频音频", "原视频的音频", "参考视频原音频", "保留背景音乐", "保持原音频", "音频不变", "原声不变")
_NEW_AUDIO=("生成新音频", "生成音频", "生成配乐", "生成背景音乐", "新增配乐", "添加配乐", "换成配乐", "更换音乐", "重新配音", "添加旁白", "新增旁白", "生成旁白", "添加配音", "生成配音", "加入配音", "配上旁白", "新增音效", "添加音效", "生成音效", "新音效", "说出以下", "人物说", "人物对白", "说台词", "念出台词", "女声配音", "男声配音")

def select_policy(prompt, assets):
    """Return mode, source ids, and an accurate plain-language explanation.

    Explicit uploads win even if old clients send an audio_mode override.
    No source video exists in text-to-video: keep provider's native sound.
    """
    assets=[a for a in (assets or []) if a]
    clips=[a for a in assets if a.get('kind')=='audio']
    videos=[a for a in assets if a.get('kind')=='video']
    if clips:
        return {'mode':'uploaded','source_ids':[x['id'] for x in clips],
                'note':f'已上传 {len(clips)} 段音频：将按上传顺序拼接为最终音轨，替换参考视频原声；在本地合成，不增加付费生成次数。',
                'reason':'uploaded_audio'}
    p=str(prompt or '').lower()
    if any(x in p for x in _SILENT) or re.search(r'\b(?:silent video|mute the (?:video|audio)|no (?:audio|sound))\b',p):
        return {'mode':'silent','source_ids':[],'note':'已明确要求静音：成片移除音轨。','reason':'explicit_silent'}
    if videos and (any(x in p for x in _ORIGINAL) or re.search(r'\b(?:keep|retain|preserve) (?:the )?(?:original|source|reference) (?:audio|sound|soundtrack)\b',p)):
        return {'mode':'original','source_ids':[videos[0]['id']], 'note':'保留参考视频原音轨；本地合成。','reason':'explicit_original'}
    new_sound=any(x in p for x in _NEW_AUDIO) or bool(re.search(r'\b(?:voice[ -]?over|narration|sound effects?|new soundtrack|add (?:background )?music|generate (?:new )?(?:audio|music)|record dialogue|spoken dialogue)\b',p))
    if new_sound:
        return {'mode':'model','source_ids':[],'note':'提示词明确提出新的声音/配音要求，由视频模型生成音频。','reason':'explicit_new_audio'}
    if videos:
        return {'mode':'original','source_ids':[videos[0]['id']], 'note':'无额外声音要求：自动保留第一段参考视频的原声音轨。','reason':'default_reference_audio'}
    return {'mode':'model','source_ids':[], 'note':'没有参考视频或上传音频，使用模型原生音频（不额外创建第二个视频任务）。','reason':'no_source_video'}


# V4.2.8.15: semantic handling only when an audio file is attached.
# "timbre" leaves the voice generated by Seedance; "content" preserves the
# uploaded waveform as the final audio, not a purported voice-cloned output.
AUDIO_REFERENCE_OPTIONS = {'timbre', 'content'}


def reference_option(requested, assets):
    clips = [a for a in (assets or []) if a and a.get('kind') == 'audio']
    if not clips:
        # A stale hidden browser selector must never affect audio-free jobs.
        return None
    choice = requested if requested not in (None, '') else 'timbre'
    if choice not in AUDIO_REFERENCE_OPTIONS:
        raise ValueError('上传音频只能选择“参考音色”或“使用上传音频的内容”，请重新预览（未扣费）。')
    return choice


def select_reference_policy(prompt, assets, requested=None):
    choice = reference_option(requested, assets)
    if choice is None:
        result = select_policy(prompt, assets)
        result['reference_option'] = None
        return result
    clips = [a for a in assets if a and a.get('kind') == 'audio']
    if choice == 'timbre':
        return {
            'mode':'model', 'source_ids':[], 'reference_option':'timbre',
            'reference_asset_ids':[a['id'] for a in clips],
            'note':'仅参考上传音频的音色；不继承原台词或背景音。使用指定台词，未指定时由视频模型生成台词。生成结果由模型决定，音色相似度需人工核查。',
            'reason':'audio_reference_timbre'
        }
    return {
        'mode':'uploaded', 'source_ids':[a['id'] for a in clips],
        'reference_option':'content', 'reference_asset_ids':[a['id'] for a in clips],
        'note':'将上传音频按顺序作为最终音轨，要求模型画面与原台词同步；原声音由本地合成精确保留，口型同步程度需人工核查。',
        'reason':'audio_reference_content'
    }


def reference_instructions(option, refs):
    """Append after automatic prompt expansion so this semantic choice wins.

    Aliases are positional per audio content item and generated from the exact
    spec order; do not read words / music from the uploaded sample via ASR.
    """
    if option is None:
        return ''
    aliases = [f'@audio{i}' for i, a in enumerate([a for a in refs if a and a.get('kind') == 'audio'], 1)]
    if not aliases:
        raise ValueError('音色选项已开启但没有音频素材，本次不会调用付费接口。')
    joined='、'.join(aliases)
    if option == 'timbre':
        return ('【上传音频用途：仅参考音色（最高优先级）】仅参考'+joined+
                '的人声音色特征（音高、音质、口音、语气特征），将该声音用于本次人物对白或旁白。'
                '严禁照搬、引用或复述音频里的原始台词、语言内容、配乐、环境音和音效；'
                '对白内容必须使用用户在视频提示词明确提供的新台词，若没有提供台词，由视频模型依据视频创意自动编写自然台词。'
                '同一人物尽量保持声音一致；画面人物开口时尽量同步口型。'
                '这不是原始音轨插入任务，不得把参考文件作为最终成片音轨。')
    return ('【上传音频用途：使用音频原始内容及音色（最高优先级）】'+joined+
            '是本次生成的原始发声内容、台词及音色依据。禁止重写、替换、添加或翻译已有台词，'
            '不得更换说话人音色。根据原音频的实际时间顺序设计人物动作与口型，'
            '尽量与原台词、停顿和语气保持同步。最终音轨由本地保留上传的原始音频，'
            '不要额外创作另一条相互冲突的人声。')


def ensure_reference_audio_exists(asset_ids, lookup):
    for aid in asset_ids or []:
        row=lookup(aid)
        if not row or row.get('kind')!='audio' or not Path(row.get('path') or '').is_file():
            raise ValueError('音色参考素材不存在或已丢失；请重新上传后再预览（未产生费用）。')
        if not media.probe(Path(row['path'])).get('has_audio'):
            raise ValueError('音色参考素材没有有效音轨；请重新选择音频（未产生费用）。')


def validate_content_duration(policy, video_duration):
    if policy.get('reference_option') != 'content':
        return
    length=sum(float(row.get('duration') or 0) for row in policy.get('source_rows', []))
    if length > float(video_duration)+0.20:
        raise ValueError(f'上传音频共 {length:.1f} 秒，超过预计视频 {video_duration:.1f} 秒。保留原台词会被截断，请缩短音频或延长视频（未产生费用）。')


def validate(mode, source_id, asset_lookup, source_ids=None):
    mode=normalize(mode)
    if mode not in ('original','uploaded'):return None
    ids=list(source_ids or ([source_id] if source_id else []))
    if not ids:raise ValueError('音轨来源缺失，请重新上传参考素材再预览（未产生费用）。')
    if not media.ffmpeg_path():raise ValueError('音轨合成需要 FFmpeg，请先安装后重新预览（未产生费用）。')
    rows=[]
    for aid in ids:
        source=asset_lookup(aid)
        if not source or source.get('kind')!=('audio' if mode=='uploaded' else 'video'):
            raise ValueError('音轨引用已失效，请重新上传对应素材（未产生费用）。')
        path=Path(source.get('path') or '')
        if not path.is_file():raise ValueError('音频来源文件已丢失，请重新上传素材（未产生费用）。')
        if not media.probe(path).get('has_audio'):
            raise ValueError('音频来源没有可读取的音轨，请重新上传（未产生费用）。')
        rows.append(source)
    return rows[0] if len(rows)==1 else rows


def apply(raw_path, mode, source_id, asset_lookup, *, source_ids=None, timeout=180, target_resolution=None):
    """Return an independently saved output file; never change/delete raw_path.
    On failure the raw video remains for no-cost local reprocessing.
    """
    mode=normalize(mode)
    raw=Path(raw_path)
    if not raw.is_file() or not raw.stat().st_size:raise ValueError('原始生成视频不存在或为空')
    # For H3 this optional export tier differs from its native provider tier.
    # Existing video requests without target_resolution behave exactly as before.
    resize_to={ '480p':480,'720p':720,'1080p':1080 }.get(str(target_resolution or '').lower())
    if mode=='model' and resize_to is None:return raw
    ff=media.ffmpeg_path()
    if not ff:raise ValueError('音轨合成需要 FFmpeg（视频生成结果已保存，不需要重新付费生成）')
    info=media.probe(raw)
    dur=float(info.get('duration') or 0)
    if dur<=0:raise ValueError('无法读取生成视频时长，已保留原始生成视频，等待本地修复')
    # Always output MP4. Keep the original raw file for local, free retries.
    suffix=('_reference_audio' if mode=='original' else '_uploaded_audio' if mode=='uploaded' else '_silent' if mode=='silent' else '_model_audio')
    if resize_to is not None:suffix+='_'+str(resize_to)+'p'
    out=raw.with_name(raw.stem+suffix+'.mp4')
    temp=raw.with_name(raw.stem+'_audio_processing.mp4')
    if temp.exists():temp.unlink()
    video_codec=['-c:v','copy']
    if resize_to is not None:
        w=int(info.get('width') or 0);h=int(info.get('height') or 0)
        if min(w,h)<resize_to:
            raise ValueError(f'模型实际只返回{w}x{h}，不足以无损缩至短边{resize_to}像素；原视频已保留，不做未经确认的放大。')
        if w<=h:
            new_w=resize_to;new_h=int(round(h*resize_to/w/2))*2
        else:
            new_h=resize_to;new_w=int(round(w*resize_to/h/2))*2
        video_codec=['-vf',f'scale={new_w}:{new_h}:flags=lanczos','-c:v','libx264','-preset','medium','-crf','18','-pix_fmt','yuv420p']
    args=[ff,'-hide_banner','-loglevel','error','-nostdin','-y','-i',str(raw)]
    if mode in ('original','uploaded'):
        sources=validate(mode,source_id,asset_lookup,source_ids=source_ids)
        sources=sources if isinstance(sources,list) else [sources]
        # Never quietly truncate a user's source dialogue if a provider returns
        # a clip shorter than requested. Keep the paid original for free repair.
        if mode=='uploaded':
            total_source_duration=sum(float(media.probe(Path(s['path'])).get('duration') or s.get('duration') or 0) for s in sources)
            if total_source_duration>dur+0.20:
                raise ValueError(f'模型实际返回视频 {dur:.2f}s，短于上传音频 {total_source_duration:.2f}s；为保护全部原台词，已保留未处理视频，不会截断原声音轨。')
        for source in sources:args.extend(['-i',str(source['path'])])
        if len(sources)==1:
            args.extend(['-map','0:v:0','-map','1:a:0',*video_codec,
                        '-c:a','aac','-b:a','192k','-af','apad','-t',f'{dur:.3f}',
                        '-movflags','+faststart',str(temp)])
        else:
            ins=''.join(f'[{i}:a:0]' for i in range(1,len(sources)+1))
            audio_filter=f'{ins}concat=n={len(sources)}:v=0:a=1[cat];[cat]apad[aout]'
            args.extend(['-filter_complex',audio_filter,'-map','0:v:0','-map','[aout]',
                         *video_codec,'-c:a','aac','-b:a','192k',
                         '-t',f'{dur:.3f}', '-movflags','+faststart',str(temp)])
    elif mode=='silent':
        args.extend(['-map','0:v:0',*video_codec,'-an','-movflags','+faststart',str(temp)])
    else:
        args.extend(['-map','0:v:0','-map','0:a?','-c:a','aac','-b:a','192k',*video_codec,'-movflags','+faststart',str(temp)])
    opts=media._hidden_subprocess_kwargs() if hasattr(media,'_hidden_subprocess_kwargs') else {}
    try:
        run=subprocess.run(args,capture_output=True,timeout=timeout,**opts)
        if run.returncode or not temp.exists() or temp.stat().st_size==0:
            raise RuntimeError((run.stderr or b'').decode('utf-8','replace')[-650:] or '音轨合成没有产生有效文件')
        result=media.probe(temp)
        if mode in ('original','uploaded') and result.get('has_audio') is False:
            raise RuntimeError('合成输出缺少音频流')
        if resize_to is not None and min(int(result.get('width') or 0),int(result.get('height') or 0))!=resize_to:
            raise RuntimeError('导出尺寸校验失败，原模型视频已保留')
        if mode=='silent' and result.get('has_audio'):
            raise RuntimeError('无声模式输出仍存在音频流')
        os.replace(temp,out)
        return out
    finally:
        if temp.exists():temp.unlink()
